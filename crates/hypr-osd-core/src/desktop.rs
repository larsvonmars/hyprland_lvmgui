//! The Hyprland tab's settings, written out as Lua.
//!
//! The settings window's second tab edits Hyprland's own options - the gaps, the
//! border, the blur, the keyboard layout - and the Display page edits its monitor
//! rules: the resolution, position, scale and rotation of each connected output.
//! This module is the half that turns both into something the compositor can be
//! handed. Hyprland is configured in Lua since 0.55, so "applying" a setting means
//! calling [`hl.config`](https://wiki.hypr.land/Configuring/) with a table, and a
//! display setting means one `hl.monitor` call:
//!
//! ```lua
//! hl.config({
//!     general = { gaps_in = 5 },
//! })
//! hl.monitor({ output = "eDP-1", mode = "2736x1824@59.96", scale = "2" })
//! ```
//!
//! Two things about that are deliberate:
//!
//! * **Only the keys somebody has set are written.** The document is generated
//!   from `~/.config/hypr-osd/desktop.conf`, which starts empty, so an untouched
//!   machine gets `hl.config({})` and *nothing* of the user's own config is
//!   overridden. The window can grow a setting without changing the behaviour of
//!   anyone who never opens it.
//! * **The keys are Hyprland's option paths.** `general:gaps_in` is the key in
//!   the config file, because that is also what `hyprctl getoption` takes and what
//!   the value the window shows next to a row was read from; the path is what
//!   becomes the nesting here (`general = { gaps_in = 5 }`).
//!
//! The document is *idempotent and complete*: it always holds every set key, so
//! re-applying it after one change is the same thing as applying that change (see
//! the element's `apply`).

use std::collections::BTreeMap;

use crate::settings::Kind;

/// The file the Hyprland tab's keys live in, under `~/.config/hypr-osd/` - one
/// file for the whole desktop, because the desktop is handed over in one
/// document.
pub const FILE: &str = "desktop";

/// The name of the generated Lua document, next to the user's own `hyprland.lua`
/// (so `~/.config/hypr/hypr-osd-desktop.lua`).
pub const LUA: &str = "hypr-osd-desktop.lua";

/// What the generated document says before the settings: why it exists, that it
/// is not to be edited, and how it is loaded.
const HEADER: &str = "\
-- Generated by hypr-osd-settings from ~/.config/hypr-osd/desktop.conf.
-- Do not edit: the settings window's Hyprland tab rewrites this file and hands it
-- to the compositor (`hyprctl eval 'dofile(\"...\")'`) as you change a value, and
-- it holds *only* the settings that tab manages - everything else is yours.
--
-- The first call carries Hyprland's own options (`general:gaps_out` becomes
-- `general = { gaps_out = 20 }`); the `hl.monitor` calls after it carry the
-- Display page's output rules. Loaded by ~/.config/hypr/osd.lua, so it is part of
-- the session's config. It is applied after the rest of the config (osd.lua is
-- required at the end of hyprland.lua), which is what makes a value set here win
-- over one set by hand.

";

/// One output's monitor rule: where a monitor sits, how it is scaled, and so on.
///
/// The fields are `(name, kind, value)` exactly as the Display page has them -
/// `mode = "2560x1440@59.95"` - and the output is the connector the rule is for.
/// The kind only decides how the value is spelled, the same way it does for
/// [`lua_document`]'s options.
pub struct MonitorRule<'a> {
    pub output: &'a str,
    pub fields: Vec<(&'a str, Kind, &'a str)>,
}

/// The Lua document for the settings that are set: one `hl.config` call with the
/// options nested the way Hyprland's option paths say, then one `hl.monitor` call
/// per output.
///
/// `entries` is `(option path, kind, value)` and `monitors` is the Display page's
/// rules; the kind only decides how a value is spelled (a switch is `true`, a
/// number is bare, text is a quoted string). An empty pair of lists produces
/// `hl.config({})`, which is a valid document that says nothing - and, in
/// particular, *no* monitor rules, so a machine that has never opened the Display
/// page keeps whatever its own `hyprland.lua` says.
pub fn lua_document(entries: &[(&str, Kind, &str)], monitors: &[MonitorRule]) -> String {
    lua_document_with(HEADER, entries, monitors)
}

/// The same document with a caller's own header.
///
/// The header is the only part that says *who* wrote the file and why, and two
/// programs write to this compositor: the settings window (the desktop document)
/// and the energy daemon (the effect document). Everything else about the shape
/// is identical on purpose - one nesting rule, one spelling of a value, one
/// stable order - so a reader who understands one understands the other.
pub fn lua_document_with(
    header: &str,
    entries: &[(&str, Kind, &str)],
    monitors: &[MonitorRule],
) -> String {
    let mut tree: BTreeMap<String, Node> = BTreeMap::new();
    for (path, kind, value) in entries {
        let parts: Vec<&str> = path.split(':').collect();
        insert(&mut tree, &parts, literal(*kind, value));
    }

    let mut body = String::new();
    render(&tree, 1, &mut body);
    let mut document = format!("{header}hl.config({{\n{body}}})\n");
    for rule in monitors {
        document.push_str(&monitor_line(rule));
    }
    document
}

/// One `hl.monitor({...})` call, on its own line.
///
/// The output comes first because that is what the rule is *about*, and the fields
/// follow in the order the caller gave them - so the line reads like the rule it
/// is, and the same rule always produces the same bytes.
fn monitor_line(rule: &MonitorRule) -> String {
    let mut line = format!("\nhl.monitor({{ output = {}", quote(rule.output));
    for (field, kind, value) in &rule.fields {
        line.push_str(&format!(
            ", {} = {}",
            table_key(field),
            literal(*kind, value)
        ));
    }
    line.push_str(" })\n");
    line
}

/// One node of the option tree: a value, or a table of them.
enum Node {
    Leaf(String),
    Table(BTreeMap<String, Node>),
}

/// Put one value at its path, creating the tables along the way.
///
/// A path that is *both* a value and a table (`general = 1` and
/// `general:gaps_in = 5`) cannot be expressed in Lua; the deeper one wins, because
/// the deeper one is the option that actually exists. A test holds the catalogue
/// to paths that cannot collide this way in the first place.
fn insert(tree: &mut BTreeMap<String, Node>, path: &[&str], literal: String) {
    let Some((head, rest)) = path.split_first() else {
        return;
    };
    if rest.is_empty() {
        tree.insert((*head).to_string(), Node::Leaf(literal));
        return;
    }
    let node = tree
        .entry((*head).to_string())
        .or_insert_with(|| Node::Table(BTreeMap::new()));
    if matches!(node, Node::Leaf(_)) {
        *node = Node::Table(BTreeMap::new());
    }
    if let Node::Table(children) = node {
        insert(children, rest, literal);
    }
}

/// Write a table out, one option per line.
///
/// The map is ordered, so the document is *stable* - the same settings produce
/// the same bytes, which is what makes it readable in a diff and impossible to
/// mistake for something that changed.
fn render(tree: &BTreeMap<String, Node>, depth: usize, out: &mut String) {
    let indent = "    ".repeat(depth);
    for (key, node) in tree {
        match node {
            Node::Leaf(literal) => {
                out.push_str(&format!("{indent}{} = {literal},\n", table_key(key)));
            }
            Node::Table(children) => {
                out.push_str(&format!("{indent}{} = {{\n", table_key(key)));
                render(children, depth + 1, out);
                out.push_str(&format!("{indent}}},\n"));
            }
        }
    }
}

/// A table key: bare when Lua can read it as a name, `["…"]` when it cannot -
/// Hyprland has option names like `tap-to-click`, and they have to survive.
fn table_key(key: &str) -> String {
    let bare = !key.is_empty()
        && !key
            .chars()
            .next()
            .is_some_and(|first| first.is_ascii_digit())
        && key.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
    if bare {
        key.to_string()
    } else {
        format!("[{}]", quote(key))
    }
}

/// How a value of this kind is spelled in Lua.
fn literal(kind: Kind, value: &str) -> String {
    match kind {
        Kind::Bool => {
            let on = matches!(
                value.trim().to_ascii_lowercase().as_str(),
                "true" | "yes" | "on" | "1"
            );
            on.to_string()
        }
        Kind::Int { .. } => match value.trim().parse::<i64>() {
            // A number is a number; anything unreadable is handed over as text
            // rather than dropped, so a mistake is visible in the document.
            Ok(number) => number.to_string(),
            Err(_) => quote(value.trim()),
        },
        Kind::Fraction { .. } => match value.trim().parse::<f64>() {
            // `5.00` is written as `5`, which Hyprland reads the same way and a
            // person reads more easily.
            Ok(number) if number.is_finite() => format!("{number}"),
            _ => quote(value.trim()),
        },
        Kind::Text => quote(value),
        // A name out of a list is a string like any other - the list only decides
        // how it was *chosen*. A display's scale is the one that may also be a
        // number (`scale = 2`), which Hyprland accepts either way.
        Kind::Choice(_) | Kind::Keymap(_) | Kind::Monitor(_) => quote(value),
        // A path is a string: no Hyprland option takes one today, but if the
        // Hyprland tab ever grows one, this is what would be written.
        Kind::Path | Kind::PathFolder => quote(value),
        // A colour is `#rrggbb` and a font is a family name - both strings, for the
        // same reason.
        Kind::Color | Kind::Font => quote(value),
        // Neither of these is ever an entry in a document: a reading is not a
        // setting, and a button writes no key. Handing the value over as text is
        // the harmless answer if one ever is, rather than dropping it silently.
        Kind::Info | Kind::Actions(_) => quote(value),
    }
}

/// A Lua string literal for a config value.
///
/// Escapes the two characters that would end it, plus the line break and tab -
/// the whole list a value in a `key = value` file can plausibly contain. (Lua's
/// own `\u{…}` and `\ddd` escapes are deliberately not produced: nothing here
/// needs them, and a reader should be able to see the value in the document.)
fn quote(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for character in value.chars() {
        match character {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            other => out.push(other),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn options_are_nested_the_way_their_paths_say() {
        let document = lua_document(
            &[
                (
                    "general:gaps_in",
                    Kind::Int {
                        min: 0,
                        max: 100,
                        step: 1,
                    },
                    "5",
                ),
                ("decoration:blur:enabled", Kind::Bool, "true"),
                ("input:kb_layout", Kind::Text, "ch"),
                (
                    "input:kb_variant",
                    Kind::Keymap(crate::keymap::Keymap::Variant),
                    "de",
                ),
                (
                    "input:accel_profile",
                    Kind::Choice(&["adaptive", "flat"]),
                    "flat",
                ),
            ],
            &[],
        );
        assert!(document.contains("hl.config({\n"));
        assert!(document.contains("        gaps_in = 5,"), "{document}");
        assert!(document.contains("        blur = {\n"), "{document}");
        assert!(
            document.contains("            enabled = true,"),
            "{document}"
        );
        assert!(
            document.contains("        kb_layout = \"ch\","),
            "{document}"
        );
        assert!(
            document.contains("        kb_variant = \"de\","),
            "{document}"
        );
        assert!(
            document.contains("        accel_profile = \"flat\","),
            "{document}"
        );
    }

    /// Several keys of one table end up in the *same* table - that is the whole
    /// job of walking the paths - and the tables come out in a stable order.
    #[test]
    fn keys_of_one_section_share_its_table() {
        let entries = [
            (
                "decoration:rounding",
                Kind::Int {
                    min: 0,
                    max: 40,
                    step: 1,
                },
                "10",
            ),
            (
                "decoration:blur:size",
                Kind::Int {
                    min: 1,
                    max: 20,
                    step: 1,
                },
                "3",
            ),
            ("decoration:shadow:enabled", Kind::Bool, "false"),
        ];
        let document = lua_document(&entries, &[]);
        assert_eq!(document.matches("decoration = {").count(), 1, "{document}");

        // Order is the map's, so the same settings always produce the same file.
        assert_eq!(document, lua_document(&entries, &[]));
        let blur = document.find("blur = {").unwrap();
        let shadow = document.find("shadow = {").unwrap();
        let rounding = document.find("rounding = 10").unwrap();
        assert!(blur < rounding && rounding < shadow, "{document}");
    }

    #[test]
    fn nothing_set_is_an_empty_config_call() {
        let document = lua_document(&[], &[]);
        assert!(document.ends_with("hl.config({\n})\n"), "{document}");
        // The header still says what the file is, so an empty one is not a
        // mystery.
        assert!(document.starts_with("-- Generated by hypr-osd-settings"));
        assert!(document.contains("Do not edit"));
        // An untouched Display page writes no monitor rule at all: the
        // compositor keeps whatever its own config says.
        assert!(
            !document.lines().any(|line| line.starts_with("hl.monitor")),
            "{document}"
        );
    }

    /// A monitor rule becomes one `hl.monitor` call, with the output quoted and
    /// the values spelled by their kind (`scale = "2"` is a string, `transform = 0`
    /// a number, `disabled = false` a switch).
    #[test]
    fn a_monitor_rule_is_one_call_per_output() {
        let document = lua_document(
            &[],
            &[
                MonitorRule {
                    output: "eDP-1",
                    fields: vec![
                        (
                            "mode",
                            Kind::Monitor(crate::settings::MonitorList::Mode),
                            "2736x1824@59.96",
                        ),
                        ("position", Kind::Text, "1903x1440"),
                        (
                            "scale",
                            Kind::Monitor(crate::settings::MonitorList::Scale),
                            "2",
                        ),
                        (
                            "transform",
                            Kind::Int {
                                min: 0,
                                max: 7,
                                step: 1,
                            },
                            "0",
                        ),
                        (
                            "mirror",
                            Kind::Monitor(crate::settings::MonitorList::Mirror),
                            "none",
                        ),
                        ("disabled", Kind::Bool, "false"),
                    ],
                },
                MonitorRule {
                    output: "DP-1",
                    fields: vec![("mode", Kind::Text, "2560x1440@59.95")],
                },
            ],
        );
        assert!(
            document.contains(
                "hl.monitor({ output = \"eDP-1\", mode = \"2736x1824@59.96\", \
                 position = \"1903x1440\", scale = \"2\", transform = 0, \
                 mirror = \"none\", disabled = false })"
            ),
            "{document}"
        );
        assert!(
            document.contains("hl.monitor({ output = \"DP-1\", mode = \"2560x1440@59.95\" })"),
            "{document}"
        );
    }

    #[test]
    fn values_are_spelled_the_way_lua_reads_them() {
        // Fractions lose their trailing zeroes, text is quoted, switches are
        // true/false whatever the file spelled them.
        assert_eq!(literal(Kind::Fraction { min: 0.0, max: 1.0 }, "1.00"), "1");
        assert_eq!(
            literal(Kind::Fraction { min: 0.0, max: 2.0 }, "0.17"),
            "0.17"
        );
        assert_eq!(literal(Kind::Bool, "yes"), "true");
        assert_eq!(literal(Kind::Bool, "0"), "false");
        assert_eq!(
            literal(Kind::Text, "grp:alt_shift_toggle"),
            "\"grp:alt_shift_toggle\""
        );
        // A value with a quote in it cannot end the string it is in.
        assert_eq!(literal(Kind::Text, "a\"b\\c"), "\"a\\\"b\\\\c\"");
        // A text value that looks like a number stays text where the *kind* says
        // it is text, and a broken number is passed on rather than dropped.
        assert_eq!(literal(Kind::Text, "5"), "\"5\"");
        assert_eq!(
            literal(
                Kind::Int {
                    min: 0,
                    max: 9,
                    step: 1
                },
                "x"
            ),
            "\"x\""
        );
    }

    #[test]
    fn an_option_name_lua_cannot_read_becomes_a_bracket_key() {
        assert_eq!(table_key("gaps_in"), "gaps_in");
        assert_eq!(table_key("tap-to-click"), "[\"tap-to-click\"]");
        assert_eq!(table_key("2fast"), "[\"2fast\"]");
        assert_eq!(table_key(""), "[\"\"]");
    }
}
