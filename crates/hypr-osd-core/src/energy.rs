/// One desktop effect the policy can drop, and what it is worth then.
///
/// A setting may cover more than one key - switching transparency off means
/// *both* opacities become 1.0 - which is why the mapping is a table of keys
/// rather than one entry per switch.
pub struct Effect {
    /// The Hyprland option path the daemon writes, e.g. `decoration:blur:enabled`,
    /// which is the same spelling the settings window's Hyprland tab uses and
    /// what `hyprctl getoption` takes.
    pub key: &'static str,
    /// The policy key in `energy.conf` that asks for this drop.
    pub setting: &'static str,
    /// The value written while energy is being saved.
    pub saving: &'static str,
    /// Hyprland's own value - the fallback baseline when nothing was remembered
    /// (a machine with no compositor to read, or a first run that could not ask).
    pub default: &'static str,
    pub kind: Kind,
}

