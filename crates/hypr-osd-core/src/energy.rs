/// The values the machine had before the daemon first dropped an effect.
///
/// Read off the *running compositor* rather than out of any file, because the
/// machine's own `hyprland.lua` is the thing being overridden and it says things
/// this collection does not know about. It is written to a state file when the
/// saving profile takes hold, so a daemon restarted mid-save still knows what to
/// put back.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Baseline {
    /// Whether the values below are currently in force *because of us*.
    pub saving: bool,
    values: Vec<(String, String)>,
}

impl Baseline {
    /// What the machine had `key` at, if it was remembered.
    pub fn value(&self, key: &str) -> Option<&str> {
        self.values
            .iter()
            .find(|(name, _)| name == key)
            .map(|(_, value)| value.as_str())
    }

    /// How many values were remembered - zero before the first time a saving
    /// profile was entered.
    pub fn remembered(&self) -> usize {
        self.values.len()
    }

    /// Read every effect key off the compositor. Keys it does not answer for are
    /// left out, so [`desired`] falls back to the table's own default instead of
    /// writing an empty value.
    pub fn capture() -> Baseline {
        Baseline {
            saving: true,
            values: EFFECTS
                .iter()
                .filter_map(|effect| {
                    hyprctl::option(effect.key)
                        .map(|reading| (effect.key.to_string(), reading.value))
                })
                .collect(),
        }
    }

    pub fn load(path: &Path) -> Option<Baseline> {
        let text = fs::read_to_string(path).ok()?;
        let mut lines = text.lines();
        let saving = match lines.next()?.trim() {
            "saving" => true,
            "normal" => false,
            _ => return None,
        };
        let values = lines
            .filter_map(|line| {
                let (key, value) = line.split_once('=')?;
                Some((key.trim().to_string(), value.trim().to_string()))
            })
            .collect();
        Some(Baseline { saving, values })
    }

    pub fn save(&self, path: &Path) -> std::io::Result<()> {
        let mut text = String::from(if self.saving { "saving\n" } else { "normal\n" });
        for (key, value) in &self.values {
            text.push_str(&format!("{key} = {value}\n"));
        }
        fs::write(path, text)
    }
}

/// Where the baseline is remembered: the session's runtime directory, because a
/// runtime override belongs to the session and is glued to it at login anyway.
pub fn state_path() -> PathBuf {
    std::env::var_os("XDG_RUNTIME_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(std::env::temp_dir)
        .join("hypr-osd-energy.state")
}

/// The file the daemon writes the effect document to: under the collection's own
/// config directory, because it is a runtime artifact of `energy.conf` rather than
/// something a person edits or the compositor loads at login (see [`crate::config::dir`]).
pub const LUA: &str = "energy.lua";

/// Where that document goes.
pub fn lua_path() -> PathBuf {
    crate::config::dir().join(LUA)
}

