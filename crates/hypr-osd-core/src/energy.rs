//! Energy saving: which power profile the machine is in, and which of the
//! desktop's expensive effects are worth dropping while it is set to save.
//!
//! The desktop has one thing to save that costs nothing but a redraw - the
//! compositor's own eye candy - and power-profiles-daemon is the natural thing
//! to hang it on: when the machine is in `power-saver`, blur, shadows, opacity
//! and animations buy very little and cost GPU time on an integrated chip.
//!
//! Two halves live here, and both are shared:
//!
//! * the *policy* - which effects to drop, and which profile triggers it - read
//!   from `~/.config/hypr-osd/energy.conf` (the settings window's System tab);
//! * the *composition* - what each effect key should be worth right now, and the
//!   Lua document that says so - used by `hypr-osd-energy`, the small daemon that
//!   enforces it.
//!
//! Two rules make the daemon safe to run unattended:
//!
//! * **The values it overrides are remembered before it overrides them.** The
//!   first time the saving profile takes hold, every effect key is read back off
//!   the running compositor (see [`Baseline`]) - so the machine's *own*
//!   hand-written `hyprland.lua` comes back exactly as it was, rather than a
//!   catalogue default being mistaken for it.
//! * **The document holds every key every time.** There is no "unset" in
//!   Hyprland, so leaving the saving state means *writing the remembered values
//!   back*, not removing the overrides - which is what keeps the two halves
//!   composable with the settings window's own document (see [`document`]).

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::Duration;

use crate::config::Config;
use crate::desktop;
use crate::hyprctl;
use crate::settings::Kind;

/// The profiles power-profiles-daemon knows, quietest first - the same order the
/// system popup's segmented switch lays them out in. The first is the default
/// trigger, because it is the one word that means "save energy".
pub const PROFILES: [&str; 3] = ["power-saver", "balanced", "performance"];

/// The profile a fresh install watches for.
pub const DEFAULT_PROFILE: &str = "power-saver";
/// Whether the daemon acts at all when nobody has said otherwise.
pub const DEFAULT_ENABLED: bool = true;
/// How often the active profile is re-read, in milliseconds.
pub const DEFAULT_POLL_MS: u64 = 4000;

/// The header of the document the daemon hands the compositor. The settings
/// window's own document says the same kind of thing (see [`crate::desktop`]),
/// which matters because the two are applied to the same compositor at different
/// times and a reader has to be able to tell them apart.
pub const HEADER: &str = "\
-- Generated by hypr-osd-energy from ~/.config/hypr-osd/energy.conf.
-- Do not edit: the energy-saving daemon rewrites this file whenever the power
-- profile changes, and hands it to the compositor. It holds *only* the effect
-- keys the policy manages, at the values that are right for the current
-- profile - the values the machine had before the first time a saving profile
-- was entered are remembered in $XDG_RUNTIME_DIR/hypr-osd-energy.state.
";

