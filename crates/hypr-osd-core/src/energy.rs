    /// The driver parser picks the section the `*` marks, and prefers the CPU
    /// driver over the platform one.
    #[test]
    fn the_driver_comes_from_the_active_section() {
        // The shape `powerprofilesctl list` really prints on this desktop.
        let listing = "\
  balanced:
    CpuDriver:  intel_pstate
    PlatformDriver:     platform_profile

* performance:
    CpuDriver:  amd-pstate-epp
    PlatformDriver:     platform_profile

  power-saver:
    CpuDriver:  intel_pstate
";
        assert_eq!(
            parse_active_driver(listing).as_deref(),
            Some("amd-pstate-epp")
        );
        // A machine that reports no CPU driver still gets the platform one.
        let platform_only = "* balanced:\n    PlatformDriver:     platform_profile\n";
        assert_eq!(
            parse_active_driver(platform_only).as_deref(),
            Some("platform_profile")
        );
        assert_eq!(parse_active_driver(""), None);
    }

