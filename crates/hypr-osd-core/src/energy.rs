/// One entry of the document: the option path, how to spell the value, and the
/// value.
pub type Entry = (&'static str, Kind, String);

/// What every effect key should be worth, given the policy, the remembered
/// baseline and whether energy is being saved right now.
///
/// A switch that is off leaves its keys at the baseline - "do not drop this
/// effect" rather than "set it to something" - which is what makes a policy of
/// only some switches honest.
pub fn desired(policy: &Policy, baseline: &Baseline, saving: bool) -> Vec<Entry> {
    EFFECTS
        .iter()
        .map(|effect| {
            let value = if saving && policy.wants(effect.setting) {
                effect.saving.to_string()
            } else {
                baseline
                    .value(effect.key)
                    .unwrap_or(effect.default)
                    .to_string()
            };
            (effect.key, effect.kind, value)
        })
        .collect()
}

/// Does the compositor already have exactly these values? Compared as *numbers*
/// where that is what the option is (`1.0` and `1` are the same opacity), and as
/// trimmed text otherwise, because that is how a re-apply would be read back.
pub fn agrees(entries: &[Entry], live: &[(String, String)]) -> bool {
    entries.iter().all(|(key, kind, want)| {
        let Some((_, have)) = live.iter().find(|(name, _)| name == key) else {
            return false;
        };
        same(*kind, want, have)
    })
}

/// Whether two spellings of one option mean the same thing.
fn same(kind: Kind, want: &str, have: &str) -> bool {
    match kind {
        Kind::Bool => bool_of(want) == bool_of(have),
        Kind::Int { .. } => match (want.trim().parse::<i64>(), have.trim().parse::<i64>()) {
            (Ok(a), Ok(b)) => a == b,
            _ => want.trim() == have.trim(),
        },
        Kind::Fraction { .. } => match (want.trim().parse::<f64>(), have.trim().parse::<f64>()) {
            (Ok(a), Ok(b)) => (a - b).abs() < 1e-6,
            _ => want.trim() == have.trim(),
        },
        _ => want.trim() == have.trim(),
    }
}

/// The same truth table [`desktop::lua_document`] uses for a switch.
fn bool_of(value: &str) -> bool {
    matches!(
        value.trim().to_ascii_lowercase().as_str(),
        "true" | "yes" | "on" | "1"
    )
}

/// The document for these values: one `hl.config` call, the same shape the
/// settings window writes, and deliberately *not* the settings window's file -
/// the two are applied to the same compositor but generated by different
/// programs, and each is complete on its own, so the last one to be handed over
/// is the whole truth.
pub fn document(entries: &[Entry]) -> String {
    let refs: Vec<(&str, Kind, &str)> = entries
        .iter()
        .map(|(key, kind, value)| (*key, *kind, value.as_str()))
        .collect();
    desktop::lua_document_with(HEADER, &refs, &[])
}

