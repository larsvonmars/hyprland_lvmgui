/// The policy keys that are *switches* - one per effect setting, deduplicated
/// because two keys can share one switch (`flatten_opacity`).
///
/// Derived from [`EFFECTS`] rather than written out again, so a new effect
/// cannot arrive without its switch.
pub fn switches() -> Vec<&'static str> {
    let mut names: Vec<&'static str> = Vec::new();
    for effect in EFFECTS {
        if !names.contains(&effect.setting) {
            names.push(effect.setting);
        }
    }
    names
}

/// What `energy.conf` says: whether the daemon acts, which profile it watches,
/// how often, and which effects it may drop.
#[derive(Clone, Debug, PartialEq)]
pub struct Policy {
    pub enabled: bool,
    pub profile: String,
    pub poll: Duration,
    /// `(setting, on)` for every switch in [`EFFECTS`], in the table's order.
    pub switches: Vec<(&'static str, bool)>,
}

impl Policy {
    /// Read the policy. An absent file means "act, on power-saver, drop
    /// everything" - the whole point of the element, so the deliberate opt-out
    /// is writing `enabled = false` down.
    pub fn load(config: &Config) -> Self {
        Policy {
            enabled: config.bool("enabled", DEFAULT_ENABLED),
            profile: config.string("profile", DEFAULT_PROFILE),
            poll: config.millis("poll_ms", DEFAULT_POLL_MS),
            switches: switches()
                .into_iter()
                .map(|setting| (setting, config.bool(setting, true)))
                .collect(),
        }
    }

    /// Is this switch on? A name the table does not carry is off, which is the
    /// safe answer for a key nobody asked for.
    pub fn wants(&self, setting: &str) -> bool {
        self.switches
            .iter()
            .find(|(name, _)| *name == setting)
            .is_some_and(|(_, on)| *on)
    }
}

impl Default for Policy {
    fn default() -> Self {
        Policy {
            enabled: DEFAULT_ENABLED,
            profile: DEFAULT_PROFILE.to_string(),
            poll: Duration::from_millis(DEFAULT_POLL_MS),
            switches: switches().into_iter().map(|name| (name, true)).collect(),
        }
    }
}

/// Is the machine in the profile this policy watches *and* willing to act?
///
/// `active` is what `powerprofilesctl get` said, or `None` when the daemon does
/// not answer - which is deliberately *not* saving: a machine without
/// power-profiles-daemon keeps its effects rather than losing them silently.
pub fn saving(policy: &Policy, active: Option<&str>) -> bool {
    policy.enabled && active.is_some_and(|profile| profile == policy.profile)
}

